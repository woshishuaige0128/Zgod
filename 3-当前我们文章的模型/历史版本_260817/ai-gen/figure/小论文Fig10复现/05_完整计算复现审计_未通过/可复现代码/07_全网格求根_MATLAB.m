function summary = run_board20_step8e_fullgrid_matlab(execution_mode)
%RUN_BOARD20_STEP8E_FULLGRID_MATLAB 四候选六模型链31x67全网格。
%
% 输入仅为步骤8C索引及其中R01--R04的24个候选MAT。R05/R06在任何
% 网格分配或候选MAT加载前被硬拒绝。本文件独立实现gamma相似缩放的
% 2n+l+j阶标量延迟线最小增广，不调用步骤8D函数，不读取论文边界、
% 历史稳定域掩膜或历史曲线。

    if nargin < 1
        execution_mode = 'sentinel_only';
    end
    execution_mode = validatestring(execution_mode, ...
        {'sentinel_only', 'full'}, mfilename, 'execution_mode');
    script_path = [mfilename('fullpath'), '.m'];
    code_dir = fileparts(script_path);
    board_dir = fileparts(code_dir);
    python_root = fullfile(board_dir, 'outputs', ...
        'step8c_六链模型生成', 'python');
    index_path = fullfile(python_root, '六路线六候选索引.csv');
    output_dir = fullfile(board_dir, 'outputs', ...
        'step8e_四候选全网格', 'matlab');
    assert(isfile(index_path), 'Board20Step8E:IndexMissing', ...
        '缺少步骤8C索引：%s', index_path);
    if ~isfolder(output_dir)
        [made, message] = mkdir(output_dir);
        assert(made, 'Board20Step8E:OutputDirectoryCreateFailed', ...
            '无法创建输出目录%s：%s', output_dir, message);
    end

    paths = struct( ...
        'admission', fullfile(output_dir, 'MATLAB候选准入门禁.csv'), ...
        'sentinel', fullfile(output_dir, 'MATLAB固定性能哨兵.csv'), ...
        'points', fullfile(output_dir, 'MATLAB全网格逐点摘要.csv'), ...
        'certificate', fullfile(output_dir, 'MATLAB边界证书.csv'), ...
        'arrays', fullfile(output_dir, 'MATLAB全网格科学数组.mat'), ...
        'summary', fullfile(output_dir, 'MATLAB步骤8E摘要.json'), ...
        'log', fullfile(output_dir, 'MATLAB步骤8E运行日志.txt'), ...
        'report', fullfile(output_dir, 'MATLAB步骤8E中文报告.md'), ...
        'hashes', fullfile(output_dir, 'MATLAB哈希清单.csv'));
    path_names = fieldnames(paths);
    for path_index = 1:numel(path_names)
        exact_path = paths.(path_names{path_index});
        if isfile(exact_path)
            delete(exact_path);
        end
    end
    log_line(paths.log, sprintf('步骤8E MATLAB开始；execution_mode=%s。', ...
        execution_mode));
    log_line(paths.log, ['输入策略：仅步骤8C索引与R01--R04候选MAT；' ...
        '禁止PDF、论文边界与历史掩膜。']);

    %% 在网格分配和候选MAT加载前完成准入/拒绝硬门。
    index_table = readtable(index_path, 'TextType', 'string', ...
        'VariableNamingRule', 'preserve');
    assert(height(index_table) == 36, 'Board20Step8E:IndexCountMismatch', ...
        '步骤8C索引必须恰有36行，实际为%d。', height(index_table));
    candidate_id = string(index_table.candidate_id);
    eligible_mask = ismember(candidate_id, ["R01", "R02", "R03", "R04"]);
    diagnostic_mask = ismember(candidate_id, ["R05", "R06"]);
    assert(all(eligible_mask | diagnostic_mask), ...
        'Board20Step8E:UnexpectedCandidate', ...
        '步骤8C索引出现R01--R06之外候选。');
    assert(nnz(eligible_mask) == 24 && nnz(diagnostic_mask) == 12, ...
        'Board20Step8E:AdmissionCountMismatch', ...
        '必须准入24个R01--R04并拒绝12个R05/R06。');
    assert(all(index_table.paper_grid_eligible(eligible_mask) == ...
        "ELIGIBLE_SOURCE_COMPLETION"), ...
        'Board20Step8E:EligibleTextMismatch', ...
        'R01--R04必须标记ELIGIBLE_SOURCE_COMPLETION。');
    assert(all(index_table.paper_grid_eligible(diagnostic_mask) == ...
        "BLOCKED_DIAGNOSTIC_ONLY"), ...
        'Board20Step8E:DiagnosticTextMismatch', ...
        'R05/R06必须标记BLOCKED_DIAGNOSTIC_ONLY。');
    assert(all(index_table.formula_status(eligible_mask) == ...
        "FORMULA_COHERENT_SOURCE_COMPLETION"), ...
        'Board20Step8E:EligibleFormulaMismatch', ...
        'R01--R04公式状态不符合准入合同。');
    assert(all(index_table.formula_status(diagnostic_mask) == ...
        "HISTORICAL_DIAGNOSTIC_NOT_FORMULA_VALID"), ...
        'Board20Step8E:DiagnosticFormulaMismatch', ...
        'R05/R06公式状态不符合拒绝合同。');

    admission_status = repmat("REJECTED_DIAGNOSTIC_ONLY", height(index_table), 1);
    admission_status(eligible_mask) = "ACCEPTED_FULL_GRID";
    rejection_reason = repmat( ...
        "R05_R06_HISTORICAL_DIAGNOSTIC_NOT_FORMULA_VALID", ...
        height(index_table), 1);
    rejection_reason(eligible_mask) = "";
    admission_table = table(index_table.bundle_id, candidate_id, ...
        index_table.division, index_table.method, index_table.dimension, ...
        index_table.paper_grid_eligible, index_table.formula_status, ...
        admission_status, rejection_reason, index_table.relative_path, ...
        'VariableNames', {'bundle_id', 'candidate_id', 'division', ...
        'method', 'dimension', 'paper_grid_eligible', 'formula_status', ...
        'admission_status', 'rejection_reason', 'relative_path'});
    writetable(admission_table, paths.admission, 'Encoding', 'UTF-8');
    log_line(paths.log, ...
        '准入门完成：R01--R04共24包；R05/R06共12包已在MAT加载前拒绝。');

    eligible_table = index_table(eligible_mask, :);
    method_order = zeros(height(eligible_table), 1);
    method_order(eligible_table.method == "Original") = 1;
    method_order(eligible_table.method == "Guyan") = 2;
    method_order(eligible_table.method == "Craig_Bampton") = 3;
    assert(all(method_order > 0), 'Board20Step8E:UnknownMethod', ...
        '准入候选包含未知方法。');
    candidate_order = double(extractAfter(eligible_table.candidate_id, 1));
    [~, eligible_order] = sortrows([double(eligible_table.division), ...
        method_order, candidate_order], [1, 2, 3]);
    eligible_table = eligible_table(eligible_order, :);
    method_order = method_order(eligible_order);
    candidate_order = candidate_order(eligible_order);
    expected_route_keys = expected_route_key_list();
    actual_route_keys = compose('D%d_M%d_R%02d', ...
        double(eligible_table.division), method_order, candidate_order);
    assert(isequal(cellstr(actual_route_keys), expected_route_keys), ...
        'Board20Step8E:RouteSortContractMismatch', ...
        '24组路线未满足固定division-method-candidate键排序。');

    %% 拒绝门完成后才加载24个准入MAT并准备独立最小增广合同。
    packages = repmat(empty_package(), 24, 1);
    for package_index = 1:24
        packages(package_index) = load_and_prepare_package( ...
            python_root, eligible_table(package_index, :), ...
            method_order(package_index), candidate_order(package_index));
    end
    assert(numel(unique({packages.bundle_id})) == 24, ...
        'Board20Step8E:DuplicateBundleId', '准入bundle_id不唯一。');
    log_line(paths.log, '24个准入MAT加载并完成共享左向量/秩一/gamma合同门。');

    [parallel_enabled, worker_count] = ensure_parallel_pool();
    log_line(paths.log, sprintf('并行状态：enabled=%d，workers=%d。', ...
        parallel_enabled, worker_count));

    %% 固定性能哨兵：24组各10点，先运行并报告估时。
    sentinel_points = [0, 0; 1, 0; 0, 1; 3, 7; 10, 20; ...
        15, 33; 30, 66; 1, 48; 1, 57; 1, 64];
    sentinel_cells = cell(24, 1);
    sentinel_wall_start = tic;
    if parallel_enabled
        parfor package_index = 1:24
            sentinel_cells{package_index} = compute_sentinels( ...
                packages(package_index), package_index, sentinel_points);
        end
    else
        for package_index = 1:24
            sentinel_cells{package_index} = compute_sentinels( ...
                packages(package_index), package_index, sentinel_points);
        end
    end
    sentinel_wall_seconds = toc(sentinel_wall_start);
    sentinel_records = vertcat(sentinel_cells{:});
    sentinel_table = struct2table(sentinel_records);
    writetable(sentinel_table, paths.sentinel, 'Encoding', 'UTF-8');
    sentinel_pass = all(strcmp({sentinel_records.point_status}, 'PASS'));
    sentinel_state_max = max([sentinel_records.max_state_residual]);
    full_order_cube = expected_full_order_cube(packages);
    sentinel_order_cube = sum([sentinel_records.minimal_order].^3);
    estimated_full_seconds = sentinel_wall_seconds * ...
        full_order_cube / sentinel_order_cube;
    naive_point_scaled_seconds = sentinel_wall_seconds * 49848 / 240;
    log_line(paths.log, sprintf([ ...
        '性能哨兵完成：240/240，PASS=%d，wall=%.6fs，' ...
        '三次方加权估时=%.3fs，点数线性估时=%.3fs，最大状态残差=%.3e。'], ...
        sentinel_pass, sentinel_wall_seconds, estimated_full_seconds, ...
        naive_point_scaled_seconds, sentinel_state_max));
    if ~(sentinel_pass && isfinite(sentinel_state_max) && ...
            sentinel_state_max <= 1e-8)
        error('Board20Step8E:SentinelGateFailed', ...
            '固定性能哨兵未通过1e-8状态残差与有限根门。');
    end
    if strcmp(execution_mode, 'sentinel_only')
        summary = struct( ...
            'execution_mode', execution_mode, ...
            'sentinel_point_count', numel(sentinel_records), ...
            'sentinel_total_root_count', sum([sentinel_records.root_count]), ...
            'sentinel_maximum_state_residual', sentinel_state_max, ...
            'sentinel_wall_seconds', sentinel_wall_seconds, ...
            'estimated_full_seconds_cubic', estimated_full_seconds, ...
            'estimated_full_seconds_linear', naive_point_scaled_seconds, ...
            'sentinel_pass', sentinel_pass);
        log_line(paths.log, ...
            'sentinel_only模式按审计要求停止；未分配或计算完整网格。');
        fprintf(['步骤8E MATLAB哨兵完成：240点，roots=%d，wall=%.6fs，' ...
            '最大状态残差=%.3e；未启动完整网格。\n'], ...
            summary.sentinel_total_root_count, sentinel_wall_seconds, ...
            sentinel_state_max);
        return;
    end

    %% 完整24x31x67网格。
    package_results = cell(24, 1);
    full_wall_start = tic;
    if parallel_enabled
        parfor package_index = 1:24
            package_results{package_index} = compute_package_grid( ...
                packages(package_index), package_index);
        end
    else
        for package_index = 1:24
            package_results{package_index} = compute_package_grid( ...
                packages(package_index), package_index);
        end
    end
    full_wall_seconds = toc(full_wall_start);
    merged = merge_package_results(packages, package_results);
    assert(merged.point_count == 49848, ...
        'Board20Step8E:PointCountMismatch', ...
        '全网格必须恰有49,848点，实际为%d。', merged.point_count);
    assert(merged.total_root_count == 3356432, ...
        'Board20Step8E:RootCountMismatch', ...
        '物理根总数必须恰为3,356,432，实际为%d。', ...
        merged.total_root_count);
    full_gate = all(merged.status_code == 1) && ...
        all(isfinite(merged.root_real)) && all(isfinite(merged.root_imag)) && ...
        all(isfinite(merged.state_residual)) && ...
        max(merged.state_residual) <= 1e-8 && ...
        all(merged.root_count == merged.expected_root_count);
    log_line(paths.log, sprintf([ ...
        '全网格完成：points=%d，roots=%d，wall=%.3fs，' ...
        'max_state_residual=%.3e，gate=%d。'], ...
        merged.point_count, merged.total_root_count, full_wall_seconds, ...
        max(merged.state_residual), full_gate));
    if ~full_gate
        write_point_csv(paths.points, packages, merged);
        save_main_arrays(paths.arrays, packages, merged, struct());
        error('Board20Step8E:FullGridGateFailed', ...
            '全网格存在失败、非有限根、根数错误或状态残差超过1e-8。');
    end

    %% 固定规则自动构造边界证书并对全根做清幂多项式回代。
    [certificate_indices, reason_mask] = ...
        select_certificate_indices(merged);
    certificate_cells = cell(24, 1);
    certificate_wall_start = tic;
    if parallel_enabled
        parfor package_index = 1:24
            package_start = (package_index - 1) * 2077 + 1;
            package_end = package_start + 2076;
            local_mask = certificate_indices >= package_start & ...
                certificate_indices <= package_end;
            local_indices = certificate_indices(local_mask) - package_start + 1;
            global_indices = certificate_indices(local_mask);
            local_reasons = reason_mask(global_indices);
            certificate_cells{package_index} = compute_certificates( ...
                packages(package_index), package_results{package_index}, ...
                local_indices, global_indices, local_reasons);
        end
    else
        for package_index = 1:24
            package_start = (package_index - 1) * 2077 + 1;
            package_end = package_start + 2076;
            local_mask = certificate_indices >= package_start & ...
                certificate_indices <= package_end;
            local_indices = certificate_indices(local_mask) - package_start + 1;
            global_indices = certificate_indices(local_mask);
            local_reasons = reason_mask(global_indices);
            certificate_cells{package_index} = compute_certificates( ...
                packages(package_index), package_results{package_index}, ...
                local_indices, global_indices, local_reasons);
        end
    end
    certificate_wall_seconds = toc(certificate_wall_start);
    certificate = merge_certificate_results(certificate_cells);
    certificate_gate = certificate.count == numel(certificate_indices) && ...
        all(certificate.status_code == 1) && ...
        all(isfinite(certificate.root_real)) && ...
        all(isfinite(certificate.root_imag)) && ...
        all(isfinite(certificate.state_residual)) && ...
        all(isfinite(certificate.polynomial_residual)) && ...
        max(certificate.state_residual) <= 1e-8 && ...
        max(certificate.laurent_residual) <= 1e-8 && ...
        max(certificate.polynomial_residual) <= 1e-8 && ...
        max(certificate.independent_rho_difference) <= 1e-12;
    log_line(paths.log, sprintf([ ...
        '边界证书完成：points=%d，roots=%d，wall=%.3fs，' ...
        'max_laurent_residual=%.3e，max_poly_residual=%.3e，gate=%d。'], ...
        certificate.count, numel(certificate.root_real), ...
        certificate_wall_seconds, max(certificate.laurent_residual), ...
        max(certificate.polynomial_residual), certificate_gate));
    if ~certificate_gate
        error('Board20Step8E:CertificateGateFailed', ...
            '边界证书根数、根匹配或1e-8双残差门未通过。');
    end

    %% 按固定键排序写平面科学数组、逐点CSV与证书CSV。
    write_point_csv(paths.points, packages, merged);
    write_certificate_csv(paths.certificate, packages, merged, certificate);
    scientific_array_sha256 = science_fingerprint(packages, merged, certificate);
    save_main_arrays(paths.arrays, packages, merged, certificate, ...
        scientific_array_sha256);
    point_csv_sha256 = file_sha256(paths.points);
    certificate_csv_sha256 = file_sha256(paths.certificate);

    stable_count = nnz(merged.class_code == 1);
    critical_count = nnz(merged.class_code == 2);
    unstable_count = nnz(merged.class_code == 3);
    summary = struct( ...
        'schema', 'board20-step8e-matlab-fullgrid-v1', ...
        'input_policy', ...
            'ONLY_STEP8C_INDEX_AND_R01_R04_MAT_NO_PDF_NO_MASK', ...
        'solver', 'independent_gamma_scaled_2n_plus_l_plus_j_augmentation', ...
        'key_sort_policy', ...
            'division_method_candidate_l_j; roots_abs_real_imag', ...
        'l_values', 0:30, 'j_values', 0:66, ...
        'admitted_bundle_count', 24, ...
        'rejected_R05_R06_bundle_count', 12, ...
        'point_count', merged.point_count, ...
        'total_physical_root_count', merged.total_root_count, ...
        'expected_total_physical_root_count', 3356432, ...
        'stable_point_count', stable_count, ...
        'critical_point_count', critical_count, ...
        'unstable_point_count', unstable_count, ...
        'maximum_state_matrix_relative_residual', ...
            max(merged.state_residual), ...
        'minimum_physical_root_magnitude', ...
            min(hypot(merged.root_real, merged.root_imag)), ...
        'maximum_physical_root_magnitude', ...
            max(hypot(merged.root_real, merged.root_imag)), ...
        'certificate_point_count', certificate.count, ...
        'certificate_root_count', numel(certificate.root_real), ...
        'certificate_maximum_state_residual', ...
            max(certificate.state_residual), ...
        'certificate_maximum_laurent_residual', ...
            max(certificate.laurent_residual), ...
        'certificate_maximum_polynomial_residual', ...
            max(certificate.polynomial_residual), ...
        'certificate_maximum_independent_rho_difference', ...
            max(certificate.independent_rho_difference), ...
        'certificate_recomputation_contract', ...
            'INDEPENDENT_SECOND_EIG_ROOT_COUNT_AND_RHO_ONLY', ...
        'sentinel_point_count', numel(sentinel_records), ...
        'sentinel_maximum_state_residual', sentinel_state_max, ...
        'dynamic_timing_policy', ...
            'EXCLUDED_FROM_SCIENTIFIC_OUTPUTS_PRESENT_ONLY_IN_RUNTIME_LOG', ...
        'point_csv_sha256', point_csv_sha256, ...
        'certificate_csv_sha256', certificate_csv_sha256, ...
        'scientific_array_sha256', scientific_array_sha256, ...
        'all_points_pass', full_gate, ...
        'certificate_pass', certificate_gate, ...
        'output_files', paths);
    write_report(paths.report, summary);
    write_json_utf8(paths.summary, summary);
    write_hash_manifest(paths.hashes, script_path, index_path, packages, paths);
    log_line(paths.log, sprintf([ ...
        '步骤8E MATLAB完成：points=%d，roots=%d，certificate=%d，' ...
        'science_sha=%s。'], merged.point_count, merged.total_root_count, ...
        certificate.count, scientific_array_sha256));

    fprintf(['步骤8E MATLAB完成：49,848点，3,356,432根，' ...
        '稳定=%d，临界=%d，不稳定=%d，最大状态残差=%.3e，' ...
        '证书点=%d，最大证书多项式残差=%.3e。\n'], ...
        stable_count, critical_count, unstable_count, ...
        summary.maximum_state_matrix_relative_residual, ...
        certificate.count, summary.certificate_maximum_polynomial_residual);
end


function package = load_and_prepare_package(python_root, row, ...
        expected_method_index, expected_candidate_index)
    relative_path = char(row.relative_path);
    mat_path = fullfile(python_root, strrep(relative_path, '/', filesep));
    assert(isfile(mat_path), 'Board20Step8E:EligibleMatMissing', ...
        '准入MAT不存在：%s', mat_path);
    actual_sha = file_sha256(mat_path);
    assert(strcmpi(actual_sha, char(row.mat_sha256)), ...
        'Board20Step8E:EligibleMatHashMismatch', ...
        '准入MAT SHA不符：%s', mat_path);
    required = {'division', 'method_index', 'candidate_index', ...
        'route_dimension', 'formula_valid_code', ...
        'paper_grid_eligible_code', 'dt', 'integration_mass_operator', ...
        'C1', 'K1', 'feedback_C', 'feedback_K', ...
        'active_delay_C_left_factor', 'active_delay_C_right_factor', ...
        'active_delay_K_left_factor', 'active_delay_K_right_factor'};
    loaded = load(mat_path, required{:});
    missing = setdiff(required, fieldnames(loaded), 'stable');
    assert(isempty(missing), 'Board20Step8E:EligibleMatFieldMissing', ...
        '准入MAT缺字段：%s', strjoin(missing, ', '));
    division = exact_integer(loaded.division, 'division');
    method_index = exact_integer(loaded.method_index, 'method_index');
    candidate_index = exact_integer(loaded.candidate_index, 'candidate_index');
    n = exact_integer(loaded.route_dimension, 'route_dimension');
    assert(division == double(row.division) && ...
        method_index == expected_method_index && ...
        candidate_index == expected_candidate_index, ...
        'Board20Step8E:EligibleMatIdentityMismatch', ...
        '准入MAT身份与索引排序合同不符：%s', mat_path);
    assert(candidate_index >= 1 && candidate_index <= 4 && ...
        exact_integer(loaded.formula_valid_code, 'formula_valid_code') == 1 && ...
        exact_integer(loaded.paper_grid_eligible_code, ...
            'paper_grid_eligible_code') == 1, ...
        'Board20Step8E:EligibleMatCodeRejected', ...
        'MAT内部代码不允许进入论文全网格：%s', mat_path);
    dt = finite_positive_scalar(loaded.dt, 'dt');
    mass_operator = finite_matrix(loaded.integration_mass_operator, n, n, ...
        'integration_mass_operator');
    c1 = finite_matrix(loaded.C1, n, n, 'C1');
    k1 = finite_matrix(loaded.K1, n, n, 'K1');
    feedback_c = finite_matrix(loaded.feedback_C, n, n, 'feedback_C');
    feedback_k = finite_matrix(loaded.feedback_K, n, n, 'feedback_K');
    c_left = finite_matrix(loaded.active_delay_C_left_factor, n, 2, ...
        'active_delay_C_left_factor');
    c_right = finite_matrix(loaded.active_delay_C_right_factor, 2, n, ...
        'active_delay_C_right_factor');
    k_left = finite_matrix(loaded.active_delay_K_left_factor, n, 2, ...
        'active_delay_K_left_factor');
    k_right = finite_matrix(loaded.active_delay_K_right_factor, 2, n, ...
        'active_delay_K_right_factor');
    shared_error = zeros(1, 2);
    rank_one_error = zeros(1, 2);
    gamma = zeros(1, 2);
    u = zeros(n, 2);
    a = zeros(2, n);
    b = zeros(2, n);
    for channel = 1:2
        shared_error(channel) = norm(c_left(:, channel) - ...
            k_left(:, channel), 2) / max([norm(c_left(:, channel), 2), ...
            norm(k_left(:, channel), 2), eps('double')]);
        assert(shared_error(channel) <= 1e-12, ...
            'Board20Step8E:SharedLeftGateFailed', ...
            '共享左向量误差超过1e-12：%s channel=%d', ...
            mat_path, channel);
        u(:, channel) = c_left(:, channel);
        a(channel, :) = c_right(channel, :) / dt + k_right(channel, :);
        b(channel, :) = -c_right(channel, :) / dt;
        force_pair = [u(:, channel) * c_right(channel, :), ...
            u(:, channel) * k_right(channel, :)];
        singular_values = svd(force_pair, 'econ');
        if isscalar(singular_values)
            rank_one_error(channel) = 0;
        else
            rank_one_error(channel) = singular_values(2) / singular_values(1);
        end
        assert(isfinite(rank_one_error(channel)) && ...
            rank_one_error(channel) <= 1e-12, ...
            'Board20Step8E:RankOneGateFailed', ...
