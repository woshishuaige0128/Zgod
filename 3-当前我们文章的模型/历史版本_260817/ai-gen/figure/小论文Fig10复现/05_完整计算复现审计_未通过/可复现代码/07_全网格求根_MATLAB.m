function result = solve_point(package, l_delay, j_delay, compute_polynomial)
    result = empty_point_result();
    try
        n = package.dimension;
        delays = [double(l_delay), double(j_delay)];
        order = 2 * n + sum(delays);
        augmented = zeros(order);
        augmented(1:n, 1:n) = package.base_current;
        augmented(1:n, n + (1:n)) = package.base_previous;
        augmented(n + (1:n), 1:n) = eye(n);
        next_buffer = 2 * n + 1;
        for channel = 1:2
            delay = delays(channel);
            if delay == 0
                input = -(package.inertial \ package.u(:, channel));
                augmented(1:n, 1:n) = augmented(1:n, 1:n) + ...
                    input * package.a(channel, :);
                augmented(1:n, n + (1:n)) = ...
                    augmented(1:n, n + (1:n)) + ...
                    input * package.b(channel, :);
            else
                gamma = package.gamma(channel);
                input = -(package.inertial \ package.u(:, channel)) * gamma;
                buffer = next_buffer:(next_buffer + delay - 1);
                augmented(1:n, buffer(end)) = ...
                    augmented(1:n, buffer(end)) + input;
                augmented(buffer(1), 1:n) = package.a(channel, :) / gamma;
                augmented(buffer(1), n + (1:n)) = ...
                    package.b(channel, :) / gamma;
                if delay > 1
                    augmented(buffer(2:end), buffer(1:end-1)) = eye(delay - 1);
                end
                next_buffer = next_buffer + delay;
            end
        end
        assert(next_buffer == order + 1 && all(isfinite(augmented(:))), ...
            'Board20Step8E:AugmentationAssemblyFailed', ...
            '2n+l+j增广装配或有限性失败。');
        [vectors, diagonal] = eig(augmented);
        roots = diag(diagonal);
        assert(numel(roots) == order && ...
            all(isfinite(real(roots))) && all(isfinite(imag(roots))), ...
            'Board20Step8E:PhysicalRootsInvalid', ...
            '最小增广根数或有限性失败。');
        [~, sort_order] = sortrows([abs(roots), real(roots), imag(roots)], ...
            [1, 2, 3]);
        roots = roots(sort_order);
        vectors = vectors(:, sort_order);
        residual_matrix = augmented * vectors - ...
            vectors .* reshape(roots, 1, []);
        vector_norm = vecnorm(vectors, 2, 1);
        denominator = (norm(augmented, 'fro') + abs(roots).') .* vector_norm;
        state_residual = (vecnorm(residual_matrix, 2, 1) ./ denominator).';
        assert(all(isfinite(state_residual)) && ...
            max(state_residual) <= 1e-8, ...
            'Board20Step8E:StateResidualGateFailed', ...
            '状态矩阵逐根残差超过1e-8或非有限。');
        rho = max(abs(roots));
        dominant_indices = find(abs(roots) == rho);
        dominant = roots(dominant_indices(end));
        stable = rho < 1;
        critical = abs(rho - 1) <= 1e-8;
        if critical
            class_code = int8(2);
        elseif stable
            class_code = int8(1);
        else
            class_code = int8(3);
        end
        laurent_residual = zeros(0, 1);
        polynomial_residual = zeros(0, 1);
        if compute_polynomial
            [polynomial, laurent_exponents, laurent_coefficients] = ...
                build_cleared_polynomial(package, l_delay, j_delay);
            laurent_residual = zeros(order, 1);
            polynomial_residual = zeros(order, 1);
            for root_index = 1:order
                laurent_residual(root_index) = laurent_residual_one( ...
                    laurent_exponents, laurent_coefficients, ...
                    roots(root_index), vectors(1:n, root_index));
                polynomial_residual(root_index) = polynomial_residual_one( ...
                    polynomial, roots(root_index), vectors(1:n, root_index));
            end
            assert(all(isfinite(laurent_residual)) && ...
                max(laurent_residual) <= 1e-8, ...
                'Board20Step8E:LaurentResidualGateFailed', ...
                '证书原Laurent逐根残差超过1e-8或非有限。');
            assert(all(isfinite(polynomial_residual)) && ...
                max(polynomial_residual) <= 1e-8, ...
                'Board20Step8E:PolynomialResidualGateFailed', ...
                '证书清幂矩阵多项式逐根残差超过1e-8或非有限。');
        end
        result = struct('roots', roots, ...
            'state_residual', state_residual, ...
            'laurent_residual', laurent_residual, ...
            'polynomial_residual', polynomial_residual, ...
            'rho', rho, 'dominant', dominant, ...
            'stable', stable, 'critical', critical, ...
            'class_code', class_code, ...
            'max_state_residual', max(state_residual), ...
            'status', 'PASS', 'failure_identifier', '', ...
            'failure_message', '');
    catch ME
        result.failure_identifier = ME.identifier;
        result.failure_message = ME.message;
    end
end


function [polynomial, exponents, coefficients] = ...
        build_cleared_polynomial(package, l_delay, j_delay)
    [exponents, coefficients] = build_laurent_coefficients( ...
        package, l_delay, j_delay);
    clearing = max(0, -exponents(1));
    polynomial = repmat({zeros(package.dimension)}, 1, ...
        max(exponents + clearing) + 1);
    for index = 1:numel(coefficients)
        polynomial{exponents(index) + clearing + 1} = coefficients{index};
    end
    delays = [double(l_delay), double(j_delay)];
    assert(numel(polynomial) - 1 == max(delays) + 2, ...
        'Board20Step8E:PolynomialDegreeMismatch', ...
        '证书清幂矩阵多项式次数不符。');
end


function [exponents, coefficients] = build_laurent_coefficients( ...
        package, l_delay, j_delay)
    n = package.dimension;
    delays = [double(l_delay), double(j_delay)];
    exponents = -(max(delays) + 1):1;
    coefficients = repmat({zeros(n)}, 1, numel(exponents));
    coefficients = add_laurent(coefficients, exponents, 1, package.inertial);
    coefficients = add_laurent(coefficients, exponents, 0, package.b0);
    coefficients = add_laurent(coefficients, exponents, -1, package.b1);
    for channel = 1:2
        coefficients = add_laurent(coefficients, exponents, ...
            -delays(channel), package.u(:, channel) * package.a(channel, :));
        coefficients = add_laurent(coefficients, exponents, ...
            -(delays(channel) + 1), ...
            package.u(:, channel) * package.b(channel, :));
    end
    nonzero = cellfun(@(value) any(value(:) ~= 0), coefficients);
    first = find(nonzero, 1, 'first');
    last = find(nonzero, 1, 'last');
    coefficients = coefficients(first:last);
    exponents = exponents(first:last);
end


function coefficients = add_laurent(coefficients, exponents, exponent, value)
    location = find(exponents == exponent, 1);
    assert(~isempty(location), 'Board20Step8E:LaurentRangeError', ...
        'Laurent指数未分配。');
    coefficients{location} = coefficients{location} + value;
end


function residual = polynomial_residual_one(polynomial, root, vector)
    vector_norm = norm(vector, 2);
    if ~(isfinite(vector_norm) && vector_norm > 0)
        residual = Inf;
        return;
    end
    degree = numel(polynomial) - 1;
    terms = complex(zeros(numel(vector), degree + 1));
    denominator_terms = zeros(1, degree + 1);
    root_power = 1;
    for exponent = 0:degree
        terms(:, exponent + 1) = ...
            root_power * (polynomial{exponent + 1} * vector);
        denominator_terms(exponent + 1) = abs(root_power) * ...
            norm(polynomial{exponent + 1}, 'fro') * vector_norm;
        root_power = root_power * root;
    end
    [~, summation_order] = sort(vecnorm(terms, 2, 1), 'ascend');
    numerator = norm(sum(terms(:, summation_order), 2), 2);
    denominator = sum(denominator_terms);
    if denominator == 0
        residual = Inf;
    else
        residual = numerator / denominator;
    end
end


function residual = laurent_residual_one(exponents, coefficients, root, vector)
% 对原Laurent方程按逐项对数幅值归一化，避免小根的负幂上溢。
    root_abs = abs(root);
    vector_norm = norm(vector, 2);
    if ~(isfinite(root_abs) && root_abs > 0 && ...
            isfinite(vector_norm) && vector_norm > 0)
        residual = Inf;
        return;
    end
    term_count = numel(exponents);
    log_root_abs = log(root_abs);
    root_angle = angle(root);
    denominator_logs = -Inf(1, term_count);
    term_logs = -Inf(1, term_count);
    term_directions = complex(zeros(numel(vector), term_count));
    for index = 1:term_count
        coefficient = coefficients{index};
        coefficient_denominator = norm(coefficient, 'fro') * vector_norm;
        product = coefficient * vector;
        product_norm = norm(product, 2);
        if coefficient_denominator > 0
            denominator_logs(index) = log(coefficient_denominator) + ...
                exponents(index) * log_root_abs;
        end
        if product_norm > 0
            term_logs(index) = log(product_norm) + ...
                exponents(index) * log_root_abs;
            term_directions(:, index) = product / product_norm;
        end
    end
    scale_log = max(denominator_logs);
    if ~isfinite(scale_log)
        residual = Inf;
        return;
    end
    scaled_terms = complex(zeros(numel(vector), term_count));
    for index = 1:term_count
        if isfinite(term_logs(index))
            phase = exp(1i * exponents(index) * root_angle);
            scaled_terms(:, index) = exp(term_logs(index) - scale_log) * ...
                phase * term_directions(:, index);
        end
    end
    [~, summation_order] = sort(vecnorm(scaled_terms, 2, 1), 'ascend');
    numerator = norm(sum(scaled_terms(:, summation_order), 2), 2);
    denominator = sum(exp(denominator_logs - scale_log));
    if ~(isfinite(numerator) && isfinite(denominator) && denominator > 0)
        residual = Inf;
    else
        residual = numerator / denominator;
    end
end


