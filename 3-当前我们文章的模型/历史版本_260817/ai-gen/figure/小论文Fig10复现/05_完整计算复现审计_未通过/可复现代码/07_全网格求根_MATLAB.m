    determinism_scope = {'DETERMINISTIC_INPUT'; 'DETERMINISTIC_INPUT'};
    for package_index = 1:24
        roles{end + 1, 1} = sprintf('eligible_mat_%02d', package_index); %#ok<AGROW>
