        gamma(channel) = max([norm(a(channel, :), 2), ...
            norm(b(channel, :), 2), eps('double')]);
    end
    inertial = mass_operator / (dt ^ 2);
    assert(rcond(inertial) > eps('double'), ...
        'Board20Step8E:SingularInertialOperator', ...
        'T数值奇异：%s', mat_path);
