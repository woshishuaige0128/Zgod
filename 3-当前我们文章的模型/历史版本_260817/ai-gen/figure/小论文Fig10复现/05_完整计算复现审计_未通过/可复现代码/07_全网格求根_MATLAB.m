function hash_value = file_sha256(path_value)
    file_id = fopen(path_value, 'rb');
    assert(file_id >= 0, 'Board20Step8E:HashOpenFailed', ...
        '无法读取待哈希文件：%s', path_value);
    cleanup = onCleanup(@() fclose(file_id));
    digest = java.security.MessageDigest.getInstance('SHA-256');
    while true
        bytes = fread(file_id, 1024 * 1024, '*uint8');
        if isempty(bytes)
            break;
        end
        digest.update(typecast(bytes(:), 'int8'));
    end
    raw = typecast(digest.digest(), 'uint8');
    hash_value = upper(reshape(dec2hex(raw, 2).', 1, []));
    clear cleanup;
end


function digest_text(digest, value)
    digest_bytes(digest, unicode2native(char(value), 'UTF-8'));
end


function digest_numeric(digest, value)
    digest_text(digest, class(value));
    digest_bytes(digest, typecast(uint64(size(value)), 'uint8'));
    digest_bytes(digest, uint8(~isreal(value)));
    if islogical(value)
        digest_bytes(digest, uint8(value(:)));
    else
        digest_bytes(digest, typecast(real(value(:)), 'uint8'));
        if ~isreal(value)
            digest_bytes(digest, typecast(imag(value(:)), 'uint8'));
        end
    end
end


function digest_bytes(digest, bytes)
    bytes = uint8(bytes(:));
    digest.update(typecast(typecast(uint64(numel(bytes)), 'uint8'), 'int8'));
    if ~isempty(bytes)
        digest.update(typecast(bytes, 'int8'));
    end
end


