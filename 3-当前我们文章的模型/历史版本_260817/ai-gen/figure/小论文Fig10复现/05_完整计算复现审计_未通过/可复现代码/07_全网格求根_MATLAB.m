        determinism_scope{end + 1, 1} = 'DETERMINISTIC_INPUT'; %#ok<AGROW>
    end
    output_fields = {'admission', 'sentinel', 'points', 'certificate', ...
        'arrays', 'summary', 'report'};
    for index = 1:numel(output_fields)
        roles{end + 1, 1} = ['output_', output_fields{index}]; %#ok<AGROW>
        file_paths{end + 1, 1} = paths.(output_fields{index}); %#ok<AGROW>
        if strcmp(output_fields{index}, 'arrays')
            determinism_scope{end + 1, 1} = ...
                'HDF5_CONTAINER_BYTES_EXCLUDED_USE_SCIENTIFIC_ARRAY_SHA'; %#ok<AGROW>
        else
            determinism_scope{end + 1, 1} = 'DETERMINISTIC_OUTPUT'; %#ok<AGROW>
        end
    end
    sha256 = cellfun(@file_sha256, file_paths, 'UniformOutput', false);
    bytes = cellfun(@file_bytes, file_paths);
