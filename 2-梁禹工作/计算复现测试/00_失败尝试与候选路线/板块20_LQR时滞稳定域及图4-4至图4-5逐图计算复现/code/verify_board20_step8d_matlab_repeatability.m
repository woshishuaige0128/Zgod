function copy_summary(source_path, destination_path)
    [copied, message] = copyfile(source_path, destination_path, 'f');
    assert(copied, 'Board20Step8DRepeatability:SummaryCopyFailed', ...
        '无法保留科学摘要副本：%s', message);
end


function value = normalize_path(path_value)
    value = strrep(path_value, '\', '/');
end


function hash_value = file_sha256(path_value)
    file_id = fopen(path_value, 'rb');
    assert(file_id >= 0, 'Board20Step8DRepeatability:HashOpenFailed', ...
        '无法读取待哈希文件：%s', path_value);
    cleanup = onCleanup(@() fclose(file_id));
    digest = java.security.MessageDigest.getInstance('SHA-256');
    while true
        bytes = fread(file_id, 1024 * 1024, '*uint8');
        if isempty(bytes)
            break;
        end
        digest.update(typecast(bytes(:), 'int8'));
    end
    raw_digest = typecast(digest.digest(), 'uint8');
    hash_value = upper(reshape(dec2hex(raw_digest, 2).', 1, []));
    clear cleanup;
end


function write_json_utf8(path_value, value)
    encoded = jsonencode(value, 'PrettyPrint', true);
    file_id = fopen(path_value, 'w', 'n', 'UTF-8');
    assert(file_id >= 0, 'Board20Step8DRepeatability:JsonOpenFailed', ...
        '无法写入JSON：%s', path_value);
    cleanup = onCleanup(@() fclose(file_id));
    count = fwrite(file_id, encoded, 'char');
    assert(count == strlength(string(encoded)), ...
        'Board20Step8DRepeatability:JsonWriteFailed', ...
        'JSON未完整写入：%s', path_value);
    clear cleanup;
end
