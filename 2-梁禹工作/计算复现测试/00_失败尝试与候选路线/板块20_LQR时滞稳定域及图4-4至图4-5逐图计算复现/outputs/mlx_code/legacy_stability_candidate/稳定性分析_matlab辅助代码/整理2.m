% 给定矩阵 A
A = [1.3764    0.2185    0.2185    0.2185    0.2185;
     0.2185    0.1193    0.0134         0    0.0463;
     0.2185    0.0134    0.1193    0.0463         0;
     0.2185         0    0.0463    0.0925         0;
     0.2185    0.0463         0         0    0.0925];

% 计算 A 的特征值和特征向量
[V, D] = eig(A);

% 显示原始特征值
disp('原始特征值：');
disp(diag(D));

% 设置新的特值，这里以示例值代替，您可以设置为您想要的任何值
new_eigenvalues = [0.01, 0.05, 0.0730  0.1459  1.5171];

% 构造新的对角矩阵 D'
D_new = diag(new_eigenvalues);

% 使用原始特征向量 V 和新的对角矩阵 D_new 构造新的矩阵 A'
A_new = V * D_new * inv(V);

% 显示新的矩阵 A'
disp('新的矩阵 A'':');
disp(A_new);

% 验证新的矩阵 A' 的特征值是否为您设置的新特征值
new_A_eig = eig(A_new);
disp('新的矩阵 A'' 的特征值：');
disp(diag(new_A_eig));
