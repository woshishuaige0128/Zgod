function inside = path_is_under_any_root(path_value, roots)
    normalized_path = lower(canonical_path(path_value));
    inside = false;
    for root_index = 1:numel(roots)
        normalized_root = lower(canonical_path(roots{root_index}));
        if strcmp(normalized_path, normalized_root) || ...
                startsWith(normalized_path, [normalized_root, filesep])
            inside = true;
            return;
        end
    end
end


function assert_safe_blind_path(path_value, role)
    normalized = lower(strrep(char(path_value), '/', filesep));
    forbidden = { ...
        'plotted_data.mat', ...
        [filesep, 'evaluation', filesep], ...
        'strict_target_evaluator', ...
        '目标csv', ...
        '论文边界csv'};
    for token_index = 1:numel(forbidden)
        assert(~contains(normalized, lower(forbidden{token_index})), ...
            'Fig10MatlabVerify:ForbiddenTargetPath', ...
            '%s命中禁止目标路径标记%s：%s', ...
            role, forbidden{token_index}, path_value);
    end
    [~, ~, extension] = fileparts(path_value);
    assert(~strcmpi(extension, '.pdf'), ...
        'Fig10MatlabVerify:ForbiddenPdf', ...
        '%s不得为PDF：%s', role, path_value);
end


function log_line(path_value, message)
    file_id = fopen(path_value, 'a', 'n', 'UTF-8');
    assert(file_id >= 0, 'Fig10MatlabVerify:LogOpenFailed', ...
        '无法写入日志：%s', path_value);
    cleanup = onCleanup(@() fclose(file_id));
    fprintf(file_id, '%s | %s\n', char(datetime('now', ...
        'Format', 'yyyy-MM-dd HH:mm:ss.SSS')), message);
    clear cleanup;
end


function hash_value = file_sha256(path_value)
    file_id = fopen(path_value, 'rb');
    assert(file_id >= 0, 'Fig10MatlabVerify:HashOpenFailed', ...
        '无法读取待哈希文件：%s', path_value);
    cleanup = onCleanup(@() fclose(file_id));
    digest = java.security.MessageDigest.getInstance('SHA-256');
    while true
        bytes = fread(file_id, 1024 * 1024, '*uint8');
        if isempty(bytes)
            break;
        end
        digest.update(typecast(bytes(:), 'int8'));
    end
    raw = typecast(digest.digest(), 'uint8');
    hash_value = upper(reshape(dec2hex(raw, 2).', 1, []));
    clear cleanup;
end


function write_hash_manifest(path_value, verifier_path, manifest_path, ...
        run_summary_path, packages, source_points_paths, output_paths)
    roles = {'verifier_source'; 'blind_manifest'; 'python_run_summary'};
    file_paths = {canonical_path(verifier_path); manifest_path; run_summary_path};
    for package_index = 1:numel(packages)
        roles{end + 1, 1} = 'operator_bundle'; %#ok<AGROW>
        file_paths{end + 1, 1} = packages(package_index).bundle_path; %#ok<AGROW>
        roles{end + 1, 1} = 'python_points'; %#ok<AGROW>
        file_paths{end + 1, 1} = source_points_paths{package_index}; %#ok<AGROW>
    end
    output_names = {'points', 'routes', 'summary', 'log'};
    for output_index = 1:numel(output_names)
        roles{end + 1, 1} = 'matlab_output'; %#ok<AGROW>
        file_paths{end + 1, 1} = canonical_path( ...
            output_paths.(output_names{output_index})); %#ok<AGROW>
    end
    sha256 = cellfun(@file_sha256, file_paths, 'UniformOutput', false);
    bytes = cellfun(@file_bytes, file_paths);
    status = repmat({'HASHED'}, numel(file_paths), 1);
    output = table(string(roles), string(file_paths), bytes, ...
        string(sha256), string(status), ...
        'VariableNames', {'role', 'path', 'bytes', 'sha256', 'status'});
    writetable(output, path_value, 'Encoding', 'UTF-8');
end


