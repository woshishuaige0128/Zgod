function [rho, maximum_residual, transition_error, root_count, finite_code] = ...
        solve_minimal_point(package, l_samples, j_samples)
    n = package.dimension;
    delays = [double(l_samples), double(j_samples)];
    expected_order = 2 * n + sum(delays);
    augmented = zeros(expected_order, expected_order);
    augmented(1:n, 1:n) = -package.base_zero;
    augmented(1:n, n + (1:n)) = -package.base_minus_one;
    augmented(n + (1:n), 1:n) = eye(n);
    offset = 2 * n + 1;
    for channel = 1:2
        delay = delays(channel);
        u_vector = package.delay_left(:, channel);
        v_zero = package.delay_v_zero(channel, :);
        v_minus_one = package.delay_v_minus_one(channel, :);
        gamma = package.register_scales(channel);
        if delay == 0
            augmented(1:n, 1:n) = augmented(1:n, 1:n) - ...
                u_vector * v_zero;
            augmented(1:n, n + (1:n)) = ...
                augmented(1:n, n + (1:n)) - u_vector * v_minus_one;
        else
            registers = offset:(offset + delay - 1);
            augmented(1:n, registers(end)) = ...
                augmented(1:n, registers(end)) - u_vector * gamma;
            augmented(registers(1), 1:n) = v_zero / gamma;
            augmented(registers(1), n + (1:n)) = v_minus_one / gamma;
            if delay > 1
                augmented(registers(2:end), registers(1:end-1)) = ...
                    eye(delay - 1);
            end
            offset = offset + delay;
        end
    end
    assert(offset == expected_order + 1, ...
        'Fig10MatlabVerify:AugmentedIndexMismatch', ...
        '最小增广索引未闭合。');
    finite_matrix_code = isreal(augmented) && all(isfinite(augmented(:)));
    if ~finite_matrix_code
        rho = NaN;
        maximum_residual = Inf;
        transition_error = Inf;
        root_count = 0;
        finite_code = false;
        return;
    end

    % The native contract is a generalized state equation.  Only the top n
    % rows carry mass_term; the delay registers and previous-state rows have
    % an identity following operator.  Form the ordinary transition matrix
    % independently in MATLAB via left division before calling eig.
    transition = augmented;
    transition(1:n, :) = package.mass_term \ augmented(1:n, :);
    current_norm = norm(augmented, 'fro');
    reconstruction_top = package.mass_term * transition(1:n, :) - ...
        augmented(1:n, :);
    transition_error = norm(reconstruction_top, 'fro') / current_norm;
    finite_transition_code = all(isfinite(transition(:))) && ...
        isfinite(current_norm) && current_norm > 0.0 && ...
        isfinite(transition_error);
    if ~finite_transition_code
        rho = NaN;
        maximum_residual = Inf;
        transition_error = Inf;
        root_count = 0;
        finite_code = false;
        return;
    end

    [vectors, diagonal] = eig(transition);
    roots = diag(diagonal);
    root_count = numel(roots);
    finite_code = root_count == expected_order && ...
        all(isfinite(real(roots))) && all(isfinite(imag(roots))) && ...
        all(isfinite(real(vectors(:)))) && all(isfinite(imag(vectors(:))));
    if ~finite_code
        rho = NaN;
        maximum_residual = Inf;
        return;
    end
    following_times_vectors = vectors;
    following_times_vectors(1:n, :) = ...
        package.mass_term * vectors(1:n, :);
    residual_matrix = augmented * vectors - ...
        following_times_vectors .* roots.';
    vector_norm = vecnorm(vectors, 2, 1).';
    following_norm = sqrt(norm(package.mass_term, 'fro') ^ 2 + ...
        (expected_order - n));
    denominator = (current_norm + abs(roots) .* following_norm) .* ...
        vector_norm;
    state_residual = vecnorm(residual_matrix, 2, 1).' ./ ...
        max(denominator, realmin('double'));
    finite_code = finite_code && all(isfinite(state_residual));
    maximum_residual = max(state_residual);
    rho = max(abs(roots));
end


function route_summary = build_route_summary(packages, comparison, ...
        source_points_paths, source_points_sha256)
    route_count = numel(packages);
    route_id = strings(route_count, 1);
    contract_id = strings(route_count, 1);
    division = zeros(route_count, 1);
    method = strings(route_count, 1);
    dimension = zeros(route_count, 1);
    point_count = zeros(route_count, 1);
    matlab_stable_point_count = zeros(route_count, 1);
    python_stable_point_count = zeros(route_count, 1);
    maximum_rho_absolute_difference = NaN(route_count, 1);
    stable_mismatch_count = zeros(route_count, 1);
    maximum_state_eigenpair_residual = NaN(route_count, 1);
    maximum_transition_reconstruction_error = NaN(route_count, 1);
    minimum_rho_matlab = NaN(route_count, 1);
    maximum_rho_matlab = NaN(route_count, 1);
    bundle_sha256_match = false(route_count, 1);
    manifest_bundle_sha256 = strings(route_count, 1);
    actual_bundle_sha256 = strings(route_count, 1);
    python_points_path = strings(route_count, 1);
    python_points_sha256 = strings(route_count, 1);
    all_points_pass = false(route_count, 1);
    for route_index = 1:route_count
        package = packages(route_index);
        mask = comparison.route_id == string(package.route_id);
        route_id(route_index) = string(package.route_id);
        contract_id(route_index) = string(package.contract_id);
        division(route_index) = package.division;
        method(route_index) = string(package.method);
        dimension(route_index) = package.dimension;
        point_count(route_index) = nnz(mask);
        matlab_stable_point_count(route_index) = ...
            nnz(comparison.stable_matlab(mask));
        python_stable_point_count(route_index) = ...
            nnz(comparison.stable_python(mask));
        maximum_rho_absolute_difference(route_index) = ...
            max(comparison.rho_absolute_difference(mask));
        stable_mismatch_count(route_index) = ...
            nnz(comparison.stable_mismatch(mask));
        maximum_state_eigenpair_residual(route_index) = ...
            max(comparison.maximum_state_eigenpair_residual(mask));
        maximum_transition_reconstruction_error(route_index) = ...
            max(comparison.transition_reconstruction_error(mask));
        minimum_rho_matlab(route_index) = min(comparison.rho_matlab(mask));
        maximum_rho_matlab(route_index) = max(comparison.rho_matlab(mask));
        manifest_bundle_sha256(route_index) = ...
            string(package.expected_bundle_sha256);
        actual_bundle_sha256(route_index) = ...
            string(package.actual_bundle_sha256);
        bundle_sha256_match(route_index) = strcmp( ...
            package.expected_bundle_sha256, package.actual_bundle_sha256);
        python_points_path(route_index) = string(source_points_paths{route_index});
        python_points_sha256(route_index) = ...
            string(source_points_sha256{route_index});
        all_points_pass(route_index) = all(comparison.overall_pass(mask));
    end
    route_summary = table(route_id, contract_id, division, method, ...
        dimension, point_count, matlab_stable_point_count, ...
        python_stable_point_count, maximum_rho_absolute_difference, ...
        stable_mismatch_count, maximum_state_eigenpair_residual, ...
        maximum_transition_reconstruction_error, ...
        minimum_rho_matlab, maximum_rho_matlab, bundle_sha256_match, ...
        manifest_bundle_sha256, actual_bundle_sha256, ...
        python_points_path, python_points_sha256, all_points_pass);
end


