function [enabled, workers] = ensure_parallel_pool()
    enabled = false;
    workers = 1;
    if ~(license('test', 'Distrib_Computing_Toolbox') && ...
            ~isempty(ver('parallel')))
        return;
    end
    try
        pool = gcp('nocreate');
        if isempty(pool)
            workers_requested = min(8, max(1, feature('numcores')));
            pool = parpool('threads', workers_requested);
        end
        enabled = true;
        workers = pool.NumWorkers;
    catch
        enabled = false;
        workers = 1;
    end
end


