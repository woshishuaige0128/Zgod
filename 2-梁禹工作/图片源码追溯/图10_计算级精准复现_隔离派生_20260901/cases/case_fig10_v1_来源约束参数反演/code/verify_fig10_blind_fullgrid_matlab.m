function write_text_utf8(path_value, text_value)
    file_id = fopen(path_value, 'w', 'n', 'UTF-8');
    assert(file_id >= 0, 'Fig10MatlabVerify:TextOpenFailed', ...
        '无法写入文本：%s', path_value);
    cleanup = onCleanup(@() fclose(file_id));
    bytes = unicode2native(char(text_value), 'UTF-8');
    count = fwrite(file_id, bytes, 'uint8');
    assert(count == numel(bytes), 'Fig10MatlabVerify:TextWriteFailed', ...
        '文本未完整写入：%s', path_value);
    clear cleanup;
end
