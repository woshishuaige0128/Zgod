function summary = verify_fig10_blind_fullgrid_matlab(manifest_path, python_fullgrid_root, output_dir)
%VERIFY_FIG10_BLIND_FULLGRID_MATLAB Independently verify a six-route blind grid.
%
% This verifier is intentionally independent of the Python eigensolver.  It
% reads only a FIG10 blind-search manifest, its six MINIMAL_AUGMENTED_CORE_V1
% MAT bundles, and an already completed Python full-grid output root.  For
% every (l,j) in 0:30 x 0:66 it builds the 2*n+l+j state matrix directly in
% MATLAB, computes its eigenvalues, and compares rho/stable point by point.
%
% Forbidden inputs: plotted_data.mat, target/evaluation CSV files, PDFs, and
% the strict target evaluator.  No Python process or Python code is invoked.

    narginchk(3, 3);
    manifest_path = canonical_existing_file(manifest_path, '.json', 'manifest');
    python_fullgrid_root = canonical_existing_folder( ...
        python_fullgrid_root, 'python full-grid root');
    assert_safe_blind_path(manifest_path, 'manifest');
    assert_safe_blind_path(python_fullgrid_root, 'python full-grid root');

    output_dir = char(string(output_dir));
    assert(~isempty(strtrim(output_dir)), ...
        'Fig10MatlabVerify:EmptyOutputDirectory', 'output_dir不能为空。');
    if isfolder(output_dir)
        entries = dir(output_dir);
        names = setdiff({entries.name}, {'.', '..'});
        assert(isempty(names), 'Fig10MatlabVerify:OutputNotEmpty', ...
            '输出目录必须不存在或为空，拒绝覆盖：%s', output_dir);
    else
        [made, message] = mkdir(output_dir);
        assert(made, 'Fig10MatlabVerify:OutputCreateFailed', ...
            '无法创建输出目录%s：%s', output_dir, message);
    end
    output_dir = canonical_existing_folder(output_dir, 'output directory');
    assert_safe_blind_path(output_dir, 'output directory');

    paths = struct( ...
        'points', fullfile(output_dir, 'matlab_pointwise_comparison.csv'), ...
        'routes', fullfile(output_dir, 'matlab_route_summary.csv'), ...
        'summary', fullfile(output_dir, 'matlab_validation_summary.json'), ...
        'log', fullfile(output_dir, 'matlab_validation.log'), ...
        'hashes', fullfile(output_dir, 'artifact_hash_manifest.csv'));
    log_line(paths.log, 'MATLAB独立全网格复核开始。');
    log_line(paths.log, ['输入策略：只读盲算manifest、六个core MAT与已完成的' ...
        'Python full-grid；禁止目标数据、PDF、评价器和Python求解器。']);

    try
        manifest_sha256 = file_sha256(manifest_path);
        manifest = jsondecode(fileread(manifest_path));
        validate_manifest_header(manifest);
        routes = manifest.routes(:);
        validate_six_route_identity(routes);
        allowed_roots = json_string_list(manifest.allowed_bundle_roots, ...
            'allowed_bundle_roots');
        for root_index = 1:numel(allowed_roots)
            allowed_roots{root_index} = canonical_existing_folder( ...
                allowed_roots{root_index}, 'allowed bundle root');
            assert_safe_blind_path(allowed_roots{root_index}, ...
                'allowed bundle root');
        end

        run_summary_path = canonical_existing_file(fullfile( ...
            python_fullgrid_root, 'run_summary.json'), '.json', ...
            'python run summary');
        python_run_sha256 = file_sha256(run_summary_path);
        python_run = jsondecode(fileread(run_summary_path));
        validate_python_run_summary(python_run, manifest_sha256);

        package_count = numel(routes);
        packages = repmat(empty_package(), package_count, 1);
        source_tables = cell(package_count, 1);
        source_points_paths = cell(package_count, 1);
        source_points_sha256 = cell(package_count, 1);
        for route_index = 1:package_count
            route = routes(route_index);
            packages(route_index) = load_core_package( ...
                route, allowed_roots);
            [source_tables{route_index}, source_points_paths{route_index}, ...
                source_points_sha256{route_index}] = ...
                load_python_points(python_fullgrid_root, route, ...
                packages(route_index).dimension);
        end
        log_line(paths.log, sprintf([ ...
            '输入门通过：manifest SHA=%s；六个bundle SHA与字段均闭合；' ...
            'Python结果为PASS full-grid。'], manifest_sha256));

        l_expected = repelem((0:30).', 67);
        j_expected = repmat((0:66).', 31, 1);
        route_point_count = numel(l_expected);
        total_point_count = package_count * route_point_count;
        assert(total_point_count == 12462, ...
            'Fig10MatlabVerify:InternalPointCountMismatch', ...
            '六路线31x67必须为12462点。');

        route_index_all = repelem((1:package_count).', route_point_count);
        l_all = repmat(l_expected, package_count, 1);
        j_all = repmat(j_expected, package_count, 1);
        rho_matlab = NaN(total_point_count, 1);
        maximum_state_residual = NaN(total_point_count, 1);
        transition_reconstruction_error = NaN(total_point_count, 1);
        actual_root_count = zeros(total_point_count, 1);
        finite_code = false(total_point_count, 1);

        [parallel_enabled, worker_count] = ensure_parallel_pool();
        log_line(paths.log, sprintf( ...
            '开始MATLAB独立最小增广求解：points=%d，parallel=%d，workers=%d。', ...
            total_point_count, parallel_enabled, worker_count));
        wall_start = tic;
        if parallel_enabled
            parfor point_index = 1:total_point_count
                package = packages(route_index_all(point_index));
                [rho_matlab(point_index), ...
                    maximum_state_residual(point_index), ...
                    transition_reconstruction_error(point_index), ...
                    actual_root_count(point_index), ...
                    finite_code(point_index)] = solve_minimal_point( ...
                    package, l_all(point_index), j_all(point_index));
            end
        else
            for point_index = 1:total_point_count
                package = packages(route_index_all(point_index));
                [rho_matlab(point_index), ...
                    maximum_state_residual(point_index), ...
                    transition_reconstruction_error(point_index), ...
                    actual_root_count(point_index), ...
                    finite_code(point_index)] = solve_minimal_point( ...
                    package, l_all(point_index), j_all(point_index));
            end
        end
        elapsed_seconds = toc(wall_start);
        log_line(paths.log, sprintf( ...
            'MATLAB独立求解完成：points=%d，wall_seconds=%.6f。', ...
            total_point_count, elapsed_seconds));

        route_id = strings(total_point_count, 1);
        contract_id = strings(total_point_count, 1);
        method = strings(total_point_count, 1);
        division = zeros(total_point_count, 1);
        route_dimension = zeros(total_point_count, 1);
        route_point_order = zeros(total_point_count, 1);
        rho_python = NaN(total_point_count, 1);
        stable_python = false(total_point_count, 1);
        python_root_count = zeros(total_point_count, 1);
        python_overall_pass = false(total_point_count, 1);
        for route_index = 1:package_count
            first = (route_index - 1) * route_point_count + 1;
            last = first + route_point_count - 1;
            source = source_tables{route_index};
            package = packages(route_index);
            route_id(first:last) = string(package.route_id);
            contract_id(first:last) = string(package.contract_id);
            method(first:last) = string(package.method);
            division(first:last) = package.division;
            route_dimension(first:last) = package.dimension;
            route_point_order(first:last) = double(source.point_order);
            rho_python(first:last) = double(source.rho);
            stable_python(first:last) = logical(double(source.stable));
            python_root_count(first:last) = double(source.physical_root_count);
            python_overall_pass(first:last) = logical(double(source.overall_pass));
        end

        expected_root_count = 2 .* route_dimension + l_all + j_all;
        stable_matlab = rho_matlab < 1.0;
        rho_absolute_difference = abs(rho_matlab - rho_python);
        stable_mismatch = stable_matlab ~= stable_python;
        order_pass = actual_root_count == expected_root_count & ...
            python_root_count == expected_root_count;
        residual_pass = maximum_state_residual <= 1.0e-8;
        transition_pass = transition_reconstruction_error <= 1.0e-12;
        rho_pass = rho_absolute_difference <= 1.0e-9;
        point_pass = finite_code & isfinite(rho_matlab) & ...
            isfinite(rho_python) & python_overall_pass & order_pass & ...
            residual_pass & transition_pass & rho_pass & ~stable_mismatch;

        comparison = table(route_id, contract_id, division, method, ...
            route_dimension, route_point_order, l_all, j_all, ...
            expected_root_count, actual_root_count, python_root_count, ...
            rho_matlab, rho_python, rho_absolute_difference, ...
            stable_matlab, stable_python, stable_mismatch, ...
            maximum_state_residual, transition_reconstruction_error, ...
            finite_code, order_pass, residual_pass, transition_pass, ...
            rho_pass, python_overall_pass, point_pass, ...
            'VariableNames', {'route_id', 'contract_id', 'division', ...
            'method', 'route_dimension', 'point_order', 'l_samples', ...
            'j_samples', 'expected_root_count', 'matlab_root_count', ...
            'python_root_count', 'rho_matlab', 'rho_python', ...
            'rho_absolute_difference', 'stable_matlab', 'stable_python', ...
            'stable_mismatch', 'maximum_state_eigenpair_residual', ...
            'transition_reconstruction_error', 'finite_code', ...
            'order_pass', 'residual_pass', 'transition_pass', ...
            'rho_pass', 'python_overall_pass', 'overall_pass'});
        writetable(comparison, paths.points, 'Encoding', 'UTF-8');

        route_summary = build_route_summary(packages, comparison, ...
            source_points_paths, source_points_sha256);
        writetable(route_summary, paths.routes, 'Encoding', 'UTF-8');

        maximum_rho_difference = max(rho_absolute_difference);
        stable_mismatch_count = nnz(stable_mismatch);
        maximum_residual = max(maximum_state_residual);
        maximum_transition_error = max(transition_reconstruction_error);
        actual_total_root_count = sum(actual_root_count);
        expected_total_root_count = sum(expected_root_count);
        finite_point_count = nnz(finite_code & isfinite(rho_matlab));
        point_count_pass = total_point_count == 12462;
        finite_pass = finite_point_count == total_point_count;
        total_order_pass = actual_total_root_count == ...
            expected_total_root_count && all(order_pass);
        all_points_pass = all(point_pass);
        overall_pass = point_count_pass && finite_pass && ...
            total_order_pass && maximum_residual <= 1.0e-8 && ...
            maximum_transition_error <= 1.0e-12 && ...
            maximum_rho_difference <= 1.0e-9 && ...
            stable_mismatch_count == 0 && all_points_pass;

        if overall_pass
            status = 'PASS';
        else
            status = 'FAIL';
        end
        summary = struct( ...
            'schema_version', 'FIG10_MATLAB_INDEPENDENT_FULLGRID_V1', ...
            'status', status, ...
            'input_policy', ['BLIND_MANIFEST_CORE_MAT_AND_COMPLETED_' ...
                'PYTHON_POINTS_ONLY_NO_TARGET_NO_PDF_NO_PYTHON_SOLVER'], ...
            'solver', 'MATLAB_EIG_MINIMAL_AUGMENTED_2N_PLUS_L_PLUS_J', ...
            'manifest_path', manifest_path, ...
            'manifest_sha256', manifest_sha256, ...
            'python_fullgrid_root', python_fullgrid_root, ...
            'python_run_summary_sha256', python_run_sha256, ...
            'route_count', package_count, ...
            'point_count', total_point_count, ...
            'expected_point_count', 12462, ...
            'finite_point_count', finite_point_count, ...
            'actual_total_root_count', actual_total_root_count, ...
            'expected_total_root_count', expected_total_root_count, ...
            'maximum_rho_absolute_difference', maximum_rho_difference, ...
            'rho_tolerance', 1.0e-9, ...
            'stable_mismatch_count', stable_mismatch_count, ...
            'maximum_state_eigenpair_residual', maximum_residual, ...
            'state_residual_tolerance', 1.0e-8, ...
            'maximum_transition_reconstruction_error', ...
                maximum_transition_error, ...
            'transition_reconstruction_tolerance', 1.0e-12, ...
            'point_count_pass', point_count_pass, ...
            'finite_pass', finite_pass, ...
            'root_order_pass', total_order_pass, ...
            'rho_pass', maximum_rho_difference <= 1.0e-9, ...
            'stable_pass', stable_mismatch_count == 0, ...
            'residual_pass', maximum_residual <= 1.0e-8, ...
            'transition_reconstruction_pass', ...
                maximum_transition_error <= 1.0e-12, ...
            'all_points_pass', all_points_pass, ...
            'blind_calculation_only', true, ...
            'target_files_read', 0, ...
            'python_solver_invocations', 0, ...
            'route_summaries', table2struct(route_summary), ...
            'output_files', paths);
        write_json_utf8(paths.summary, summary);
        log_line(paths.log, sprintf([ ...
            '门禁完成：status=%s，points=%d，max_rho_diff=%.3e，' ...
            ['stable_mismatch=%d，max_residual=%.3e，' ...
             'max_transition_error=%.3e，root_order=%d。']], ...
            status, total_point_count, maximum_rho_difference, ...
            stable_mismatch_count, maximum_residual, ...
            maximum_transition_error, total_order_pass));
        log_line(paths.log, ...
            '科学输出已封闭；此行后不再改写日志，开始生成工件哈希清单。');

        verifier_path = [mfilename('fullpath'), '.m'];
        write_hash_manifest(paths.hashes, verifier_path, manifest_path, ...
            run_summary_path, packages, source_points_paths, paths);

        assert(overall_pass, 'Fig10MatlabVerify:ScientificGateFailed', ...
            ['MATLAB独立全网格复核失败：points=%d，max_rho_diff=%.3e，' ...
            'stable_mismatch=%d，max_residual=%.3e。'], ...
            total_point_count, maximum_rho_difference, ...
            stable_mismatch_count, maximum_residual);
        fprintf(['FIG10 MATLAB独立复核PASS：%d/%d点，max|rho_M-rho_P|=%.3e，' ...
            'stable差=%d，最大状态残差=%.3e。\n'], ...
            nnz(point_pass), total_point_count, maximum_rho_difference, ...
            stable_mismatch_count, maximum_residual);
    catch exception
        log_line(paths.log, sprintf('FAIL [%s] %s', ...
            exception.identifier, exception.message));
        rethrow(exception);
    end
end


function validate_manifest_header(manifest)
    required = {'schema_version', 'target_dependency', 'allowed_bundle_roots', ...
        'routes', 'sampling'};
    assert(all(isfield(manifest, required)), ...
        'Fig10MatlabVerify:ManifestFieldsMissing', ...
        '盲算manifest缺少必需字段。');
    assert(strcmp(char(string(manifest.schema_version)), ...
        'FIG10_BLIND_SEARCH_MANIFEST_V1'), ...
        'Fig10MatlabVerify:ManifestSchemaMismatch', ...
        '盲算manifest schema_version错误。');
    assert(strcmp(char(string(manifest.target_dependency)), ...
        'FORBIDDEN_BLIND_CALCULATION_ONLY'), ...
        'Fig10MatlabVerify:TargetFirewallMissing', ...
        'manifest未声明FORBIDDEN_BLIND_CALCULATION_ONLY。');
    assert(isfield(manifest.sampling, 'grid'), ...
        'Fig10MatlabVerify:GridMissing', 'manifest缺少sampling.grid。');
    grid = manifest.sampling.grid;
    assert(exact_integer(grid.l_min, 'l_min') == 0 && ...
        exact_integer(grid.l_max, 'l_max') == 30 && ...
        exact_integer(grid.j_min, 'j_min') == 0 && ...
        exact_integer(grid.j_max, 'j_max') == 66, ...
        'Fig10MatlabVerify:GridMismatch', ...
        '复核器只接受完整0:30 x 0:66盲算网格。');
end


function validate_six_route_identity(routes)
    assert(isstruct(routes) && numel(routes) == 6, ...
        'Fig10MatlabVerify:RouteCountMismatch', ...
        'manifest必须恰有六条路线。');
    required = {'route_id', 'contract_id', 'division', 'method', ...
        'dimension', 'operator_layout', 'bundle_path', 'bundle_sha256'};
    keys = strings(6, 1);
    route_ids = strings(6, 1);
    contracts = strings(6, 1);
    for route_index = 1:6
        route = routes(route_index);
        assert(all(isfield(route, required)), ...
            'Fig10MatlabVerify:RouteFieldsMissing', ...
            '第%d条路线缺少必需字段。', route_index);
        division = exact_integer(route.division, 'division');
        method = string(route.method);
        assert(ismember(method, ["Original", "Craig_Bampton", "Guyan"]), ...
            'Fig10MatlabVerify:MethodUnknown', '未知方法：%s', method);
        assert(division == 1 || division == 2, ...
            'Fig10MatlabVerify:DivisionUnknown', 'division必须为1或2。');
        assert(exact_integer(route.dimension, 'dimension') > 0, ...
            'Fig10MatlabVerify:DimensionInvalid', 'dimension必须为正整数。');
        assert(strcmp(char(string(route.operator_layout)), ...
            'MINIMAL_AUGMENTED_CORE_V1'), ...
            'Fig10MatlabVerify:OperatorLayoutMismatch', ...
            '路线%s不是MINIMAL_AUGMENTED_CORE_V1。', string(route.route_id));
        keys(route_index) = compose('D%d_%s', division, method);
        route_ids(route_index) = string(route.route_id);
        contracts(route_index) = string(route.contract_id);
    end
    expected = sort(["D1_Original"; "D1_Craig_Bampton"; "D1_Guyan"; ...
        "D2_Original"; "D2_Craig_Bampton"; "D2_Guyan"]);
    assert(isequal(sort(keys), expected), ...
        'Fig10MatlabVerify:RouteIdentityMismatch', ...
        '六路线必须覆盖两类划分与三种方法且各一次。');
    assert(numel(unique(route_ids)) == 6, ...
        'Fig10MatlabVerify:DuplicateRouteId', 'route_id必须唯一。');
    assert(numel(unique(contracts)) == 1, ...
        'Fig10MatlabVerify:MixedContracts', ...
        '一次复核的六条路线必须属于同一contract_id。');
end


function validate_python_run_summary(run_summary, manifest_sha256)
    required = {'schema_version', 'status', 'mode', 'route_count', ...
        'point_count', 'manifest_sha256', 'blind_calculation_only'};
    assert(all(isfield(run_summary, required)), ...
        'Fig10MatlabVerify:PythonSummaryFieldsMissing', ...
        'Python run_summary缺少必需字段。');
    assert(strcmp(char(string(run_summary.schema_version)), ...
        'FIG10_BLIND_SEARCH_RUN_V1') && ...
        strcmp(char(string(run_summary.status)), 'PASS') && ...
        strcmp(char(string(run_summary.mode)), 'full-grid'), ...
        'Fig10MatlabVerify:PythonRunNotComplete', ...
        'Python结果必须是PASS full-grid。');
    assert(exact_integer(run_summary.route_count, 'route_count') == 6 && ...
        exact_integer(run_summary.point_count, 'point_count') == 12462, ...
        'Fig10MatlabVerify:PythonRunCountMismatch', ...
        'Python结果必须恰有六路线、12462点。');
    assert(logical(run_summary.blind_calculation_only), ...
        'Fig10MatlabVerify:PythonBlindFlagMissing', ...
        'Python结果没有blind_calculation_only=true。');
    assert(strcmpi(char(string(run_summary.manifest_sha256)), manifest_sha256), ...
        'Fig10MatlabVerify:ManifestHashMismatch', ...
        'Python结果绑定的manifest SHA与当前manifest不一致。');
end


function package = load_core_package(route, allowed_roots)
    bundle_path = canonical_existing_file(route.bundle_path, '.mat', 'bundle');
    assert_safe_blind_path(bundle_path, 'bundle');
    assert(path_is_under_any_root(bundle_path, allowed_roots), ...
        'Fig10MatlabVerify:BundleOutsideAllowedRoots', ...
        'bundle不在manifest允许根下：%s', bundle_path);
    expected_sha = upper(char(string(route.bundle_sha256)));
    assert(numel(expected_sha) == 64 && ...
        all(ismember(expected_sha, ['0':'9', 'A':'F'])), ...
        'Fig10MatlabVerify:BundleHashMalformed', ...
        'manifest中的bundle_sha256格式错误。');
    actual_sha = file_sha256(bundle_path);
    assert(strcmp(actual_sha, expected_sha), ...
        'Fig10MatlabVerify:BundleHashMismatch', ...
        'bundle SHA-256不符：%s', bundle_path);

    required = {'dt', 'mass_term', 'base_zero', 'base_minus_one', ...
        'delay_left', 'delay_v_zero', 'delay_v_minus_one', ...
        'register_scales'};
    optional = {'route_dimension', 'dimension', 'division', 'method_code', ...
        'contract_id_code', 'bundle_schema_version', ...
        'shared_left_factor_relative_error', 'stage0_overall_pass_code'};
    inventory = whos('-file', bundle_path);
    names = {inventory.name};
    assert(all(ismember(required, names)), ...
        'Fig10MatlabVerify:BundleFieldsMissing', ...
        'bundle缺少FIG10_BLIND_CORE_V1必需字段：%s', bundle_path);
    selected_optional = optional(ismember(optional, names));
    loaded = load(bundle_path, required{:}, selected_optional{:});

    n = exact_integer(route.dimension, 'route.dimension');
    dt = finite_positive_scalar(loaded.dt, 'dt');
    mass_term = finite_real_matrix(loaded.mass_term, n, n, 'mass_term');
    base_zero = finite_real_matrix(loaded.base_zero, n, n, 'base_zero');
    base_minus_one = finite_real_matrix( ...
        loaded.base_minus_one, n, n, 'base_minus_one');
    delay_left = finite_real_matrix(loaded.delay_left, n, 2, 'delay_left');
    delay_v_zero = finite_real_matrix( ...
        loaded.delay_v_zero, 2, n, 'delay_v_zero');
    delay_v_minus_one = finite_real_matrix( ...
        loaded.delay_v_minus_one, 2, n, 'delay_v_minus_one');
    register_scales = double(loaded.register_scales(:));
    assert(numel(register_scales) == 2 && isreal(register_scales) && ...
        all(isfinite(register_scales)) && all(register_scales > 0), ...
        'Fig10MatlabVerify:RegisterScalesInvalid', ...
        'register_scales必须为两个严格正有限实数。');
    assert(rank(mass_term) == n, 'Fig10MatlabVerify:MassTermRankDeficient', ...
        'mass_term不满秩：%s', bundle_path);

    if isfield(loaded, 'route_dimension')
        assert(exact_integer(loaded.route_dimension, 'route_dimension') == n, ...
            'Fig10MatlabVerify:RouteDimensionMismatch', ...
            'MAT route_dimension与manifest不一致。');
    end
    if isfield(loaded, 'dimension')
        assert(exact_integer(loaded.dimension, 'dimension') == n, ...
            'Fig10MatlabVerify:DimensionMismatch', ...
            'MAT dimension与manifest不一致。');
    end
    division = exact_integer(route.division, 'route.division');
    if isfield(loaded, 'division')
        assert(exact_integer(loaded.division, 'division') == division, ...
            'Fig10MatlabVerify:DivisionMismatch', ...
            'MAT division与manifest不一致。');
    end
    method = char(string(route.method));
    if isfield(loaded, 'method_code')
        method_codes = struct('Original', 1, 'Guyan', 2, 'Craig_Bampton', 3);
        assert(exact_integer(loaded.method_code, 'method_code') == ...
            method_codes.(method), 'Fig10MatlabVerify:MethodCodeMismatch', ...
            'MAT method_code与manifest不一致。');
    end
    contract_id = char(string(route.contract_id));
    if isfield(loaded, 'contract_id_code') && ...
            ismember(contract_id, {'B1', 'B2', 'B3'})
        expected_contract_code = str2double(contract_id(2));
        assert(exact_integer(loaded.contract_id_code, 'contract_id_code') == ...
            expected_contract_code, ...
            'Fig10MatlabVerify:ContractCodeMismatch', ...
            'MAT contract_id_code与manifest不一致。');
    end
    if isfield(loaded, 'bundle_schema_version')
        assert(exact_integer(loaded.bundle_schema_version, ...
            'bundle_schema_version') == 1, ...
            'Fig10MatlabVerify:BundleSchemaMismatch', ...
            'bundle_schema_version必须为1。');
    end
    if isfield(loaded, 'shared_left_factor_relative_error')
        shared_error = double(loaded.shared_left_factor_relative_error);
        assert(isscalar(shared_error) && isfinite(shared_error) && ...
            shared_error <= 1.0e-10, ...
