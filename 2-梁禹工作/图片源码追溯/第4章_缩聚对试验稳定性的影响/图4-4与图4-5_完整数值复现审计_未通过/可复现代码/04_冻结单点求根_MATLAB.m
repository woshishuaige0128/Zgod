function fingerprint = scientific_records_sha256(records)
    digest = java.security.MessageDigest.getInstance('SHA-256');
    digest_update_text(digest, ...
        'board20-step8d-matlab-minimal-augmentation-scientific-records-v1');
    fields = fieldnames(records);
    digest_update_numeric(digest, double(numel(records)));
    for record_index = 1:numel(records)
        digest_update_numeric(digest, double(record_index));
        for field_index = 1:numel(fields)
            field_name = fields{field_index};
            digest_update_text(digest, field_name);
            value = records(record_index).(field_name);
            if ischar(value) || (isstring(value) && isscalar(value))
                digest_update_text(digest, char(string(value)));
            elseif isnumeric(value) || islogical(value)
                digest_update_numeric(digest, value);
            else
                error('Board20Step8D:UnsupportedFingerprintField', ...
                    '科学数组指纹不支持字段%s的类型%s。', ...
                    field_name, class(value));
            end
        end
    end
    raw_digest = typecast(digest.digest(), 'uint8');
    fingerprint = lower(reshape(dec2hex(raw_digest, 2).', 1, []));
end


function digest_update_text(digest, value)
    digest_update_bytes(digest, unicode2native(char(value), 'UTF-8'));
end


function digest_update_numeric(digest, value)
    digest_update_text(digest, class(value));
    digest_update_bytes(digest, typecast(uint64(size(value)), 'uint8'));
    digest_update_bytes(digest, uint8(~isreal(value)));
    if islogical(value)
        digest_update_bytes(digest, uint8(value(:)));
    else
        digest_update_bytes(digest, typecast(real(value(:)), 'uint8'));
        if ~isreal(value)
            digest_update_bytes(digest, typecast(imag(value(:)), 'uint8'));
        end
    end
end


function digest_update_bytes(digest, bytes)
    bytes = uint8(bytes(:));
    length_bytes = typecast(uint64(numel(bytes)), 'uint8');
    digest.update(typecast(length_bytes(:), 'int8'));
    if ~isempty(bytes)
        digest.update(typecast(bytes, 'int8'));
    end
end


