    assert(file_id >= 0, 'Board20Step8D:JsonOpenFailed', ...
        '无法写入JSON：%s', path_value);
    cleanup = onCleanup(@() fclose(file_id));
    count = fwrite(file_id, encoded, 'char');
    assert(count == strlength(string(encoded)), ...
        'Board20Step8D:JsonWriteFailed', 'JSON未完整写入：%s', path_value);
    clear cleanup;
end
